// Command clidocs writes the docs' command reference from the CLI's own help:
// a page for each command, its subcommands as sections of it, and an index with
// the global flags. The pages are MDX, as the docs site reads them.
//
// Usage:
//
//	go run ./tools/clidocs <dir>    # make docs: hivepaas-website's docs/docs/cli/commands
//
// A run replaces the pages an earlier run wrote, those of commands gone too, and
// leaves every other file in dir.
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"

	"github.com/hivepaas/hivepaas-cli/internal/cmd"
)

const (
	dirMode  = 0o750
	pageMode = 0o644 // read by the docs site's build, as any page of it
)

// marker is in every page clidocs writes: what a run replaces.
const marker = "{/* Generated by `make docs` in hivepaas-cli from the CLI's own help: " +
	"change the help there, not this page. */}"

func main() {
	if len(os.Args) != 2 { //nolint:mnd
		fmt.Fprintln(os.Stderr, "usage: clidocs <dir>")
		os.Exit(2) //nolint:mnd
	}
	if err := run(cmd.Tree(), os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "clidocs:", err)
		os.Exit(1)
	}
}

func run(root *cobra.Command, dir string) error {
	if err := os.MkdirAll(dir, dirMode); err != nil { //nolint:gosec // the directory given on the command line
		return err
	}
	if err := removeGenerated(dir); err != nil {
		return err
	}
	pages := map[string]string{"index.md": index(root)}
	position := 2
	for _, c := range root.Commands() {
		if !documented(c) {
			continue
		}
		pages[c.Name()+".md"] = page(c, position)
		position++
	}
	for name, content := range pages {
		//nolint:gosec // pages in the directory given on the command line, for the docs site to read
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), pageMode); err != nil {
			return err
		}
	}
	return nil
}

// removeGenerated removes the pages an earlier run wrote.
func removeGenerated(dir string) error {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return err
	}
	for _, e := range entries {
		if e.IsDir() || filepath.Ext(e.Name()) != ".md" {
			continue
		}
		path := filepath.Join(dir, e.Name())
		content, err := os.ReadFile(path) //nolint:gosec // a file of the directory given
		if err != nil {
			return err
		}
		if strings.Contains(string(content), marker) {
			if err := os.Remove(path); err != nil { //nolint:gosec // a page an earlier run wrote there
				return err
			}
		}
	}
	return nil
}

// documented says a command has a page or a section: not cobra's help, nor one
// hidden.
func documented(c *cobra.Command) bool {
	return c.IsAvailableCommand() && c.Name() != "help"
}

func index(root *cobra.Command) string {
	var b strings.Builder
	b.WriteString("---\nsidebar_position: 1\n" +
		"description: 'Every command of the hivepaas CLI, and the flags they all take.'\n---\n\n")
	b.WriteString(marker + "\n\n# Commands\n\n")
	b.WriteString("Every command of `" + root.Name() + "`, from its own help: `" + root.Name() +
		" <command> --help` says the same.\n\n")
	b.WriteString("| Command | What it does |\n| --- | --- |\n")
	for _, c := range root.Commands() {
		if documented(c) {
			fmt.Fprintf(&b, "| [`%s`](./%s.md) | %s |\n", c.CommandPath(), c.Name(), cell(c.Short))
		}
	}
	b.WriteString("\n## Global flags\n\nEvery command takes these:\n\n")
	b.WriteString(flagTable(root.PersistentFlags()))
	return b.String()
}

func page(c *cobra.Command, position int) string {
	var b strings.Builder
	fmt.Fprintf(&b, "---\nsidebar_label: %s\nsidebar_position: %d\ndescription: '%s'\n---\n\n",
		c.Name(), position, strings.ReplaceAll(c.Short, "'", "''"))
	b.WriteString(marker + "\n\n")
	section(&b, c, 1)
	b.WriteString("The [global flags](./index.md#global-flags) apply to every command.\n")
	return b.String()
}

// section writes a command at a heading level, then its subcommands one level
// down.
func section(b *strings.Builder, c *cobra.Command, level int) {
	fmt.Fprintf(b, "%s %s\n\n", strings.Repeat("#", min(level, 4)), c.CommandPath()) //nolint:mnd
	text := c.Long
	if text == "" {
		text = c.Short
	}
	b.WriteString(paragraphs(text))
	b.WriteString("```text\n")
	if c.Runnable() {
		b.WriteString(c.UseLine() + "\n")
	}
	if c.HasAvailableSubCommands() {
		b.WriteString(c.CommandPath() + " [command]\n")
	}
	b.WriteString("```\n\n")
	if len(c.Aliases) > 0 {
		b.WriteString("Aliases: `" + strings.Join(append([]string{c.Name()}, c.Aliases...), "`, `") + "`\n\n")
	}
	if c.Example != "" {
		b.WriteString("Examples:\n\n```bash\n" + dedent(c.Example) + "\n```\n\n")
	}
	if flags := flagsOf(c); flags.HasAvailableFlags() {
		b.WriteString("Flags:\n\n" + flagTable(flags) + "\n")
	}
	for _, sub := range c.Commands() {
		if documented(sub) {
			section(b, sub, level+1)
		}
	}
}

// paragraphs is help text as Markdown: its hard-wrapped lines joined, its
// paragraphs kept apart.
func paragraphs(text string) string {
	var b strings.Builder
	for _, p := range strings.Split(strings.TrimSpace(text), "\n\n") {
		lines := strings.Fields(strings.ReplaceAll(p, "\n", " "))
		if len(lines) > 0 {
			b.WriteString(prose(strings.Join(lines, " ")) + "\n\n")
		}
	}
	return b.String()
}

// prose escapes text for MDX outside its code spans: there { } open an
// expression and < a tag, and a * may start emphasis.
func prose(s string) string {
	parts := strings.Split(s, "`")
	if len(parts)%2 == 0 { // an unclosed span: none of it is code
		return escape(s)
	}
	for i := 0; i < len(parts); i += 2 {
		parts[i] = escape(parts[i])
	}
	return strings.Join(parts, "`")
}

var escaper = strings.NewReplacer(`\`, `\\`, "{", `\{`, "}", `\}`, "<", "&lt;", "*", `\*`)

func escape(s string) string { return escaper.Replace(s) }

// cell is text for a table cell.
func cell(s string) string {
	return strings.ReplaceAll(prose(strings.Join(strings.Fields(s), " ")), "|", `\|`)
}

// flagsOf is what a command takes besides the global flags: its own, and those
// a command between it and the root gives its subcommands.
func flagsOf(c *cobra.Command) *pflag.FlagSet {
	flags := pflag.NewFlagSet(c.Name(), pflag.ContinueOnError)
	global := c.Root().PersistentFlags()
	add := func(f *pflag.Flag) {
		if global.Lookup(f.Name) == nil && flags.Lookup(f.Name) == nil {
			flags.AddFlag(f)
		}
	}
	c.LocalFlags().VisitAll(add)
	c.InheritedFlags().VisitAll(add)
	return flags
}

func flagTable(flags *pflag.FlagSet) string {
	var b strings.Builder
	b.WriteString("| Flag | Description |\n| --- | --- |\n")
	flags.VisitAll(func(f *pflag.Flag) {
		if f.Hidden || f.Deprecated != "" {
			return
		}
		name := "--" + f.Name
		if f.Shorthand != "" && f.ShorthandDeprecated == "" {
			name = "-" + f.Shorthand + ", " + name
		}
		kind, usage := pflag.UnquoteUsage(f)
		if kind != "" {
			name += " " + kind
		}
		usage = cell(usage)
		if shown(f) {
			usage += " (default: `" + strings.ReplaceAll(f.DefValue, "|", `\|`) + "`)"
		}
		fmt.Fprintf(&b, "| `%s` | %s |\n", name, usage)
	})
	return b.String()
}

// shown says a flag's default is worth saying: not the zero value of its type.
func shown(f *pflag.Flag) bool {
	switch f.DefValue {
	case "", "false", "0", "0s", "[]", "<nil>":
		return false
	}
	return true
}

// dedent removes the indentation every line of an example shares.
func dedent(text string) string {
	lines := strings.Split(strings.Trim(text, "\n"), "\n")
	common := -1
	for _, l := range lines {
		if strings.TrimSpace(l) == "" {
			continue
		}
		n := len(l) - len(strings.TrimLeft(l, " \t"))
		if common < 0 || n < common {
			common = n
		}
	}
	for i, l := range lines {
		if len(l) >= common && common > 0 {
			lines[i] = l[common:]
		}
	}
	return strings.Join(lines, "\n")
}
