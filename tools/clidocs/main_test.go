// sample is a small tree with what the reference has to render: a long help
// with what MDX would read as code, examples, flags of each kind, an alias, a
// command with subcommands of its own, and what is hidden.
func sample() *cobra.Command {
	root := &cobra.Command{Use: "hivepaas", Short: "The client"}
	root.PersistentFlags().StringP("app", "a", "", "app, by name, key or id")
	root.PersistentFlags().StringP("output", "o", "table", "table, json or yaml")

	login := &cobra.Command{
		Use:   "login [URL]",
		Short: "Log in to an installation",
		Long: "Log in with an API key: HIVEPAAS_API_KEY is <key id>:<secret>,\n" +
			"and a value may name ${secrets.KEY} - see `hivepaas secret` for {them}.\n\n" +
			"A second paragraph.",
		Example: "  # At a terminal\n  hivepaas login https://paas.example.com\n" +
			"  hivepaas login https://paas.example.com --key-id 8b87 --with-secret < key.txt",
		Aliases: []string{"signin"},
		Run:     func(*cobra.Command, []string) {},
	}
	login.Flags().String("key-id", "", "the API key's id")
	login.Flags().Bool("with-secret", false, "read the key's secret from stdin")
	login.Flags().Duration("timeout", 30*time.Minute, "how long to wait")
	login.Flags().StringSlice("level", nil, "levels: info|warn")
	login.Flags().String("secret", "", "never shown")
	_ = login.Flags().MarkHidden("secret")

	project := &cobra.Command{Use: "project", Short: "Projects and their environments"}
	project.PersistentFlags().String("scope", "app", "whose: app, env or project")
	env := &cobra.Command{Use: "env", Short: "A project's environments"}
	add := &cobra.Command{Use: "add NAME", Short: "Add an environment", Run: func(*cobra.Command, []string) {}}
	add.Flags().Bool("yes", false, "do not ask: for a script")
	env.AddCommand(add)
	project.AddCommand(env, &cobra.Command{
		Use: "ls", Short: "List the projects", Run: func(*cobra.Command, []string) {},
	})

	hidden := &cobra.Command{Use: "secret-thing", Short: "hidden", Hidden: true, Run: func(*cobra.Command, []string) {}}
	root.AddCommand(login, project, hidden)
	root.InitDefaultHelpCmd()
	return root
}

func generate(t *testing.T, root *cobra.Command) string {
	t.Helper()
	dir := t.TempDir()
	require.NoError(t, run(root, dir))
	return dir
}

func read(t *testing.T, path string) string {
	t.Helper()
	b, err := os.ReadFile(path)
	require.NoError(t, err)
	return string(b)
}

func TestEachCommandIsAPageAndTheIndexListsThem(t *testing.T) {
	dir := generate(t, sample())

	entries, err := os.ReadDir(dir)
	require.NoError(t, err)
	var names []string
	for _, e := range entries {
		names = append(names, e.Name())
	}
	// help is cobra's own, and a hidden command is not documented.
	assert.ElementsMatch(t, []string{"index.md", "login.md", "project.md"}, names)

	index := read(t, filepath.Join(dir, "index.md"))
	assert.Contains(t, index, "| [`hivepaas login`](./login.md) | Log in to an installation |")
	assert.Contains(t, index, "| [`hivepaas project`](./project.md) | Projects and their environments |")
	assert.Contains(t, index, "## Global flags")
	assert.Contains(t, index, "| `-o, --output string` | table, json or yaml (default: `table`) |")
}

func TestAPageHasTheHelpOfItsCommand(t *testing.T) {
	login := read(t, filepath.Join(generate(t, sample()), "login.md"))

	assert.Contains(t, login, "sidebar_label: login\n")
	assert.Contains(t, login, "description: 'Log in to an installation'\n")
	assert.Contains(t, login, "# hivepaas login\n")
	// Hard-wrapped lines are one paragraph; paragraphs stay apart.
	assert.Contains(t, login, "is &lt;key id>:&lt;secret>, and a value may name $\\{secrets.KEY\\} - see "+
		"`hivepaas secret` for \\{them\\}.\n\nA second paragraph.")
	assert.Contains(t, login, "```text\nhivepaas login [URL] [flags]\n```")
	assert.Contains(t, login, "Aliases: `login`, `signin`")
	assert.Contains(t, login, "```bash\n# At a terminal\nhivepaas login https://paas.example.com\n"+
		"hivepaas login https://paas.example.com --key-id 8b87 --with-secret < key.txt\n```")
	assert.Contains(t, login, "| `--key-id string` | the API key's id |")
	assert.Contains(t, login, "| `--with-secret` | read the key's secret from stdin |")
	assert.Contains(t, login, "| `--timeout duration` | how long to wait (default: `30m0s`) |")
	assert.Contains(t, login, "| `--level strings` | levels: info\\|warn |")
	assert.NotContains(t, login, "never shown")
	assert.Contains(t, login, "[global flags](./index.md#global-flags)")
	assert.Contains(t, login, "Generated by `make docs` in hivepaas-cli")
}

func TestSubcommandsAreSectionsOfTheirCommandsPage(t *testing.T) {
	project := read(t, filepath.Join(generate(t, sample()), "project.md"))

	assert.Contains(t, project, "```text\nhivepaas project [command]\n```")
	assert.Contains(t, project, "\n## hivepaas project env\n")
	assert.Contains(t, project, "\n### hivepaas project env add\n")
	assert.Contains(t, project, "\n## hivepaas project ls\n")
	assert.Contains(t, project, "| `--yes` | do not ask: for a script |")
	assert.Less(t, strings.Index(project, "## hivepaas project env"), strings.Index(project, "## hivepaas project ls"))
}

// A flag a command gives its subcommands is in its section and in theirs; the
// global flags are only in the index, and a command without flags has no table.
func TestFlagsAGroupGivesItsSubcommandsAreWithEach(t *testing.T) {
	project := read(t, filepath.Join(generate(t, sample()), "project.md"))

	scope := "| `--scope string` | whose: app, env or project (default: `app`) |"
	assert.Equal(t, 4, strings.Count(project, scope), "project, project env, project env add, project ls")
	assert.NotContains(t, project, "--output")
	_, add, found := strings.Cut(project, "### hivepaas project env add")
	require.True(t, found)
	assert.Contains(t, add, "| `--yes` | do not ask: for a script |")
	_, env, _ := strings.Cut(project, "## hivepaas project env\n")
	env, _, _ = strings.Cut(env, "### hivepaas project env add")
	assert.Contains(t, env, scope)
	assert.NotContains(t, project, "| --- | --- |\n\n", "a table with no flag in it")
}

func TestARunReplacesThePagesItWroteAndKeepsOtherFiles(t *testing.T) {
	dir := t.TempDir()
	require.NoError(t, os.WriteFile(filepath.Join(dir, "_category_.json"), []byte("{}"), 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "gone.md"), []byte("---\n---\n\n"+marker+"\n"), 0o600))
	require.NoError(t, os.WriteFile(filepath.Join(dir, "notes.md"), []byte("# By hand\n"), 0o600))

	require.NoError(t, run(sample(), dir))

	assert.FileExists(t, filepath.Join(dir, "_category_.json"))
	assert.FileExists(t, filepath.Join(dir, "notes.md"))
	assert.NoFileExists(t, filepath.Join(dir, "gone.md"), "a command no longer in the CLI")
	assert.FileExists(t, filepath.Join(dir, "login.md"))
}

// outsideCode is a page without its front matter, fenced blocks and code
// spans: what MDX reads as Markdown, JSX and expressions.
func outsideCode(page string) string {
	page = regexp.MustCompile("(?s)^---\n.*?\n---\n").ReplaceAllString(page, "")
	page = strings.ReplaceAll(page, marker, "")
	page = regexp.MustCompile("(?s)```.*?```").ReplaceAllString(page, "")
	return regexp.MustCompile("`[^`\n]*`").ReplaceAllString(page, "")
}

// The CLI's own commands: a page for each, every subcommand in it, and nothing
// MDX would take for JSX or an expression.
func TestTheCLIsCommandsAreDocumented(t *testing.T) {
	root := cmd.Tree()
	dir := generate(t, root)

	for _, c := range root.Commands() {
		if !documented(c) {
			continue
		}
		page := read(t, filepath.Join(dir, c.Name()+".md"))
		for _, sub := range c.Commands() {
			if documented(sub) {
				assert.Contains(t, page, "# "+sub.CommandPath()+"\n", c.Name())
			}
		}
		text := outsideCode(page)
		assert.NotRegexp(t, `(^|[^\\])[{}]`, text, c.Name())
		assert.NotContains(t, text, "<", c.Name())
	}
	assert.FileExists(t, filepath.Join(dir, "deploy.md"))
	assert.FileExists(t, filepath.Join(dir, "completion.md"))
	assert.NoFileExists(t, filepath.Join(dir, "help.md"))
}
